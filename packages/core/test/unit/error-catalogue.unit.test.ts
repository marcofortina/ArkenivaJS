test('EK-ERR-001 every public error category preserves identity and masks provider diagnostics', () => {
  for (const code of Object.keys(catalogue) as ErrorCode[]) {
    const cause = new Error('private provider response');
    const error = new KitError({
      code,
      message: 'private developer message',
      cause,
      details: { payload: 'private application data' },
    });
    assert.equal(error.code, code);
    assert.equal(error.cause, cause);
    assert.equal(error.retryable, false);
    assert.deepEqual(error.toSafeJSON(), {
      code,
      message: 'The operation could not be completed safely.',
    });
    assert.deepEqual(JSON.parse(JSON.stringify({ failure: error })), {
      failure: error.toSafeJSON(),
    });
    assert.deepEqual(
      Object.keys(error).filter((name) => ['code', 'details', 'retryable'].includes(name)),
      [],
    );
    assert.throws(() => Object.assign(error, { code: 'EK_INTERNAL' }), TypeError);
  }
});
test('EK-ERR-001 public categories do not admit prefix or case variants of a valid error', () => {
  for (const code of Object.keys(catalogue)) {
    for (const invalid of [code.toLowerCase(), code + ' ', 'prefix-' + code]) {
      assert.throws(
        () => new KitError({ code: invalid as ErrorCode, message: 'Invalid code' }),
        TypeError,
      );
    }
  }
});
